# ---------- сопоставление строки со всем списком ВОР (RowMatcher, функция «а2») ----------
ROW_PROMPT_HEAD = """Ты помощник сметчика. Ниже список позиций ведомости объёмов работ (ВОР), каждая с номером K1, K2, ... \
и список строк из других документов (акт, смета), каждая с номером R1, R2, ... Для каждой строки выбери ту позицию ВОР, \
которая называет ту же работу или материал, либо ответь, что такой позиции в ВОР нет. Ты только сравниваешь названия; \
числа не считаешь и не пересчитываешь.

Правила:
- Выбирай позицию только из списка ВОР, в поле key указывай её номер (например, "K7"). Другие значения недопустимы.
- Если подходящей позиции нет или ты сомневаешься, лучше ответь key = null.
- Одинаковый смысл при разной записи (сокращения, порядок слов, «М300» и «М-300», длинная нормативная формулировка и \
краткое название) это одна позиция, если единица совпадает.
- Монтаж и демонтаж, устройство и разборка это не одна позиция.
- «Внутренние» и «наружные» работы это разные позиции.
- Разные числа в размере, диаметре, классе или марке (d12 и d8, А500 и А240, М300 и В25) это разные позиции.
- Материал и работа с этим материалом это разные позиции.
- {unknown_kind_rule}
- {grade_reference}
- Одна и та же позиция ВОР не может быть выбрана для двух разных строк одного документа без причины: выбирай самую подходящую.

Ответь только JSON вида {{"answers": [{{"row_id": 1, "key": "K3", "confidence": 0.9, "reason": "одна фраза"}}, \
{{"row_id": 2, "key": null, "confidence": 0.85, "reason": "в ВОР такой позиции нет"}}]}}. По одному элементу на каждую строку R, \
row_id это число из номера (R2 -> 2), confidence от 0 до 1."""

ROW_SCHEMA = {
    "type": "object",
    "properties": {"answers": {"type": "array", "items": {
        "type": "object",
        "properties": {"row_id": {"type": "integer"}, "key": {"type": "string", "nullable": True},
                       "confidence": {"type": "number"}, "reason": {"type": "string"}},
        "required": ["row_id", "key", "confidence", "reason"]}}},
    "required": ["answers"],
}

KIND_RU = {"work": "работа", "material": "материал"}


def row_line(prefix: str, number: int, name: str, unit, kind) -> str:
    return f"{prefix}{number}. «{name}» (единица: {unit or '-'}, вид: {KIND_RU.get(kind, 'неизвестен')})"


def build_row_prompt(rows: list, vor_items: list) -> str:
    """rows: [{name_raw, unit, kind}], vor_items: [(id, {name_raw, unit, kind})] -> текст. Номера файлов и строк не передаются."""
    head = ROW_PROMPT_HEAD.format(unknown_kind_rule=UNKNOWN_KIND_RULE, grade_reference=GRADE_REFERENCE)
    vor = "\n".join(row_line("K", int(i[1:]), v["name_raw"], v["unit"], v["kind"]) for i, v in vor_items)
    lines = "\n".join(row_line("R", n, r["name_raw"], r["unit"], r["kind"]) for n, r in enumerate(rows, 1))
    return f"{head}\n\nСписок ВОР:\n{vor}\n\nСтроки:\n{lines}"
